/* Runs the prelude in a freshly opened engine. The window's inner size and
 * the screen's are real numbers, so they go in before the script. */
void preludio_esegui(ExJsCtx *js, int dentro_w, int dentro_h)
{
    char         testa[1024];
    unsigned int sw = 0, sh = 0;
    ExJsErrore   err;
    ExJsVal      r;

    if (!js) return;
    exjs_metti(js, exjs_globale(js), "__exos_casuali",
               exjs_nativa(js, nat_casuali, 0, "__exos_casuali"));
    exjs_metti(js, exjs_globale(js), "__exos_media",
               exjs_nativa(js, nat_media, 0, "__exos_media"));
    cripto_registra(js);       /* crypto.subtle (P11) */
    ws_registra(js);           /* WebSocket (P11) */
    lav_registra(js);          /* Worker (P11) */

    ex_screen_size(&sw, &sh);
    snprintf(testa, sizeof(testa),
             "innerWidth = %d; innerHeight = %d; outerWidth = %d; outerHeight = %d;"
             "screen = { width: %u, height: %u, availWidth: %u, availHeight: %u,"
             " colorDepth: 32, pixelDepth: 32 };"
             /* ! window.open QUI E NON NEL PRELUDIO (29 settembre 2026,
              * @NAV-FINESTRA): il preludio usa le espressioni regolari, che
              * ExJs non legge, e con ExJs non gira. Questa riga la leggono
              * tutti e due. Le finestre le apre exbrowser.c dopo lo script
              * (finestre_da_script), e solo dentro un clic. */
             "__ex_apri = []; open = function (u) {"
             " __ex_apri.push(u === undefined ? 'about:blank' : String(u)); return null; };"
             /* (P11) the user-agent the servers see, the same here */
             "try { navigator.userAgent = '%s'; navigator.appVersion = '%s';"
             " navigator.platform = '%s'; navigator.vendor = ''; } catch (e) {}",
             dentro_w, dentro_h, dentro_w, dentro_h, sw, sh, sw, sh,
             agente_browser(), agente_browser() + 8, sizeof(void *) == 8 ? "Linux x86_64" : "Linux i686");
    memset(&err, 0, sizeof(err));
    if (!exjs_esegui(js, testa, (unsigned int)strlen(testa), &r, &err))
        printf("exbrowser: preludio (misure): %s\n", err.messaggio);

    memset(&err, 0, sizeof(err));
    if (!exjs_esegui(js, PRELUDIO, (unsigned int)(sizeof(PRELUDIO) - 1), &r, &err))
        printf("exbrowser: preludio, riga %d: %s\n", err.riga, err.messaggio);
    idb_registra(js);          /* indexedDB (P11), after the prelude: it uses __exos_ser */
    intl_registra(js);         /* Intl over ICU (P11) */
    wasm_registra(js);         /* WebAssembly over WAMR (P12) */
}
