# Reads the list (publicsuffix.org, MPL-2.0: data, distributed with the
# program as a table, debug/implementazione_BROWSER002.txt 10.6 and P5) and
# writes every rule - ICANN and PRIVATE sections both, as the browsers do -
# lower case, sorted by byte, in one string with a NUL after each rule and a
# table of offsets: exwin/bin/exbrowser/biscotti.c searches it with a binary
# search (psl_c_e). The rules keep their form: "com", "co.uk", "*.ck",
# "!www.ck".
# ! INTERNATIONAL NAMES TWICE: as written (UTF-8) and in punycode ("xn--"),
# because a host can reach us in either form.
# The archive and its sha256: ~/ex_os/cross_build/terze-parti/publicsuffix.
# =============================================================================
import sys


def puny(etichetta):
    if all(ord(c) < 128 for c in etichetta):
        return etichetta
    return 'xn--' + etichetta.encode('punycode').decode('ascii')


def main():
    if len(sys.argv) != 3:
        sys.exit('uso: psl-tabella.py <public_suffix_list.dat> <psl_tabella.h>')
    regole = set()
    versione = ''
    for riga in open(sys.argv[1], encoding='utf-8'):
        riga = riga.strip()
        if riga.startswith('// VERSION:'):
            versione = riga[len('// VERSION:'):].strip()
        if not riga or riga.startswith('//'):
            continue
        r = riga.split()[0].lower()
        regole.add(r)
        segno = '!' if r.startswith('!') else ''
        corpo = r[1:] if segno else r
        p = '.'.join(puny(e) if e != '*' else e for e in corpo.split('.'))
        regole.add(segno + p)
    ordinate = sorted(x.encode('utf-8') for x in regole)
    testo, posti, u = [], [], 0
    for r in ordinate:
        posti.append(u)
        testo.append(r + b'\0')
        u += len(r) + 1
    blob = b''.join(testo)
    with open(sys.argv[2], 'w', encoding='ascii') as f:
        f.write('/* build/generati/psl_tabella.h - GENERATED by tools/psl-tabella.py\n'
                ' * from the Public Suffix List (https://publicsuffix.org, MPL-2.0),\n'
                ' * version %s: %d rules, sorted by byte. Do not edit: regenerate.\n'
                ' * Used by biscotti.c (psl_c_e). */\n' % (versione or '?', len(ordinate)))
        f.write('#define PSL_N %d\n' % len(ordinate))
        f.write('static const char g_psl_testo[%d] =\n' % len(blob))
        for i in range(0, len(blob), 64):
            pezzo = blob[i:i + 64]
            f.write('    "' + ''.join('\\%03o' % c if c < 32 or c > 126 or c in (34, 92, 63)
                                     else chr(c) for c in pezzo) + '"\n')
        f.write(';\n')
        f.write('static const unsigned int g_psl_posto[PSL_N] = {\n')
        for i in range(0, len(posti), 12):
            f.write('    ' + ','.join(str(x) for x in posti[i:i + 12]) + ',\n')
        f.write('};\n')
    print('%s: %d regole, %d byte di testo (versione %s)'
          % (sys.argv[2], len(ordinate), len(blob), versione or '?'))


main()
