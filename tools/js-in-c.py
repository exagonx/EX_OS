#!/usr/bin/env python3
# =============================================================================
# tools/js-in-c.py — a JavaScript file as a C string, at build time
#
#     python3 tools/js-in-c.py file.js out.h NAME
#
# Writes `static const char NAME[] = "...";` with every byte escaped that C
# would not take as is. For EXBrowser's IndexedDB (browser_idb.js, P11): the
# JavaScript stays a .js file that an editor and a linter can read, and the
# browser carries it inside, as it does with its prelude.
# =============================================================================
import sys
src, out, nome = sys.argv[1], sys.argv[2], sys.argv[3]
b = open(src, 'rb').read()
righe = []
for riga in b.split(b'\n'):
    s = ''
    for c in riga:
        if c == 0x5c: s += '\\\\'
        elif c == 0x22: s += '\\"'
        elif c == 0x3f: s += '\\?'          # no trigraphs
        elif 0x20 <= c < 0x7f: s += chr(c)
        else: s += '\\%03o' % c
    righe.append('"' + s + '\\n"')
open(out, 'w').write('/* generated by tools/js-in-c.py from %s: do not edit */\nstatic const char %s[] =\n%s;\n'
                     % (src, nome, '\n'.join(righe)))
